#!/usr/bin/env python3
"""Builds onirun's root filesystem from an Android emulator system image.

  mkrootfs.py SYSTEM_IMG ROOTFS [--props GETPROP_DUMP] [--linkerconfig DIR] [--properties-dir DIR]

SYSTEM_IMG is the emulator's system.img (a GPT disk with a 'super' partition). The script copies the
system, system_ext, product and vendor partitions, extracts every APEX, lays out the directories
init and vold would create, generates the static SELinux tree, device-node placeholders, the APEX
info list and the linker-config tweaks onirun needs, and installs userland/data/{init.txt,
android-properties.txt, android-env.sh}.

Two things only a booted Android can provide and must be copied from a device (adb):
  --properties-dir   /dev/__properties__ (the property areas and property_info)
  --linkerconfig     /linkerconfig (ld.config.txt and the per-APEX configs)
Without them onirun still starts, but Android's libc finds no properties.

Everything written is derived from the image; nothing here is executed.
"""
import argparse, os, shutil, struct, subprocess, sys, zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
EXT4PULL = os.path.join(HERE, 'ext4pull.py')   # ext4 payloads; erofspull.py handles EROFS ones


def run(*args):
    r = subprocess.run([sys.executable, '-I', *args], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(f'{" ".join(args)}: {r.stderr.strip()[-400:]}')
    return r.stdout


def pb_name_version(data):
    i, name, ver = 0, None, 0
    while i < len(data):
        tag = data[i]; i += 1
        if tag == 0x0a:
            n = shift = 0
            while True:
                b = data[i]; i += 1; n |= (b & 0x7f) << shift; shift += 7
                if not b & 0x80: break
            name = data[i:i + n].decode(); i += n
        elif tag == 0x10:
            v = shift = 0
            while True:
                b = data[i]; i += 1; v |= (b & 0x7f) << shift; shift += 7
                if not b & 0x80: break
            ver = v
        else:
            break
    return name, ver


def pb_fields(data):
    """Top-level (field, value) pairs of a protobuf message; values are ints or bytes."""
    i, out = 0, []
    def varint():
        nonlocal i
        v = shift = 0
        while True:
            b = data[i]; i += 1; v |= (b & 0x7f) << shift; shift += 7
            if not b & 0x80: return v
    while i < len(data):
        key = varint(); f, t = key >> 3, key & 7
        if t == 0: out.append((f, varint()))
        elif t == 2: n = varint(); out.append((f, data[i:i + n])); i += n
        elif t == 1: i += 8
        elif t == 5: i += 4
        else: break
    return out


def apex_libraries_config(R, apexes):
    """nativeloader's /linkerconfig/apex.libraries.config.txt: which JNI libraries a class loader
    for an APEX jar may load from the APEX's namespace (jniLibs), and the libraries each APEX
    provides to the platform (provideNativeLibs). linkerconfig derives it from the manifests."""
    lines = ['# generated by mkrootfs.py from apex_manifest.pb (jniLibs, provideNativeLibs)']
    for name in apexes:
        mf = os.path.join(R, 'apex', name, 'apex_manifest.pb')
        if not os.path.isfile(mf):
            continue
        fs = pb_fields(open(mf, 'rb').read())
        jni = [v.decode() for f, v in fs if f == 9]
        provide = [v.decode() for f, v in fs if f == 7]
        ns = 'com_android_' + name[len('com.android.'):].replace('.', '_') if name.startswith('com.android.') else name.replace('.', '_')
        if jni:
            lines.append(f'jni {ns} {":".join(jni)}')
        if provide:
            lines.append(f'public {ns} {":".join(provide)}')
    with open(os.path.join(R, 'linkerconfig/apex.libraries.config.txt'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


def symlink(target, path):
    if os.path.lexists(path):
        if os.path.islink(path):
            return
        shutil.rmtree(path) if os.path.isdir(path) else os.remove(path)
    os.symlink(target, path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('image'); ap.add_argument('rootfs')
    ap.add_argument('--properties-dir'); ap.add_argument('--linkerconfig')
    a = ap.parse_args()
    R = os.path.abspath(a.rootfs)
    os.makedirs(R, exist_ok=True)

    # 1. Partitions, laid out like Android: /system, /system_ext, /product, /vendor, /odm
    for part, dest in (('system', 'system'), ('system_ext', 'system_ext'), ('product', 'product'), ('vendor', 'vendor')):
        src = '/system' if part == 'system' else '/'
        if not os.path.isdir(os.path.join(R, dest)):
            print('extracting', part)
            run(EXT4PULL, a.image, '-p', part, 'pull', src, os.path.join(R, dest))
        else:
            # A rootfs built up by hand may lack whole directories (it once lacked /system/fonts, so
            # no typeface loaded and FontManagerService never finished starting): fill them in.
            for line in run(EXT4PULL, a.image, '-p', part, 'ls', src).splitlines():
                f = line.split()
                if len(f) >= 3 and f[0].startswith('d') and f[2] not in ('lost+found', 'lib') and \
                        not os.path.lexists(os.path.join(R, dest, f[2])):
                    print('extracting', part, f[2])
                    run(EXT4PULL, a.image, '-p', part, 'pull', src.rstrip('/') + '/' + f[2], os.path.join(R, dest, f[2]))
    os.makedirs(os.path.join(R, 'odm'), exist_ok=True)
    symlink('/system_ext', os.path.join(R, 'system/system_ext'))
    symlink('/product', os.path.join(R, 'system/product'))
    for name, target in (('etc', '/system/etc'), ('bin', '/system/bin')):
        symlink(target, os.path.join(R, name))

    # 2. APEXes: /system/apex/*.apex and /vendor/apex/*.apex, each payload at /apex/<name>
    entries, mounts = [], []
    for src, part in (('system/apex', 'SYSTEM'), ('vendor/apex', 'VENDOR'), ('system_ext/apex', 'SYSTEM_EXT'), ('product/apex', 'PRODUCT')):
        d = os.path.join(R, src)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if not f.endswith('.apex'):
                continue
            path = os.path.join(d, f)
            name, ver = pb_name_version(zipfile.ZipFile(path).read('apex_manifest.pb'))
            dest = os.path.join(R, 'apex', name)
            if not os.path.isdir(dest):
                print('extracting apex', name)
                try:
                    run(EXT4PULL, path, 'pull', '/', dest)
                except SystemExit:
                    try:
                        run(os.path.join(HERE, 'erofspull.py'), path, 'pull', '/', dest)    # EROFS payload
                    except SystemExit as e:
                        print('  skipped:', str(e).split(': ')[-1])
                        shutil.rmtree(dest, ignore_errors=True)
                        continue
            mounts.append((name, ver, f'/{src}/{f}'))
            entries.append(f'  <apex-info moduleName="{name}" modulePath="/{src}/{f}" preinstalledModulePath="/{src}/{f}" '
                           f'versionCode="{ver}" versionName="" isFactory="true" isActive="true" provideSharedApexLibs="false" partition="{part}" '
                           f'lastUpdateMillis="{int(os.stat(path).st_mtime * 1000)}"/>')    # odrefresh asserts it is present
    with open(os.path.join(R, 'apex/apex-info-list.xml'), 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<apex-info-list>\n' + '\n'.join(entries) + '\n</apex-info-list>\n')
    # apexd learns what is active from /proc/mounts (one loop device per APEX, onirun generates the
    # lines from /oni/apex-mounts.txt) and the loop device's sysfs backing_file.
    os.makedirs(os.path.join(R, 'oni'), exist_ok=True)
    with open(os.path.join(R, 'oni/apex-mounts.txt'), 'w') as f:
        for i, (name, ver, path) in enumerate(mounts):
            f.write(f'{name} {ver} {path}\n')
            d = os.path.join(R, f'sys/block/loop{i}/loop'); os.makedirs(d, exist_ok=True)
            open(os.path.join(d, 'backing_file'), 'w').write(path + '\n')
            os.makedirs(os.path.join(R, 'dev/block'), exist_ok=True)
            open(os.path.join(R, f'dev/block/loop{i}'), 'a').close()
            symlink(name, os.path.join(R, f'apex/{name}@{ver}'))

    # 2b. Pre-compiled boot image and odex files: built for a collector that needs userfaultfd, so
    # ART can't use them; left in place they only make its stack dumper abort.
    for rel in ('system/framework/arm64', 'system/framework/oat'):
        shutil.rmtree(os.path.join(R, rel), ignore_errors=True)
    for f in os.listdir(os.path.join(R, 'system/framework')):
        if f.startswith('boot') and f.endswith('.vdex'):
            os.remove(os.path.join(R, 'system/framework', f))

    # 2c. Hardware onirun can't provide: dropping the feature declaration keeps the framework from
    # starting the stack (UWB's talks to a virtio serial port and panics without its HAL).
    for feat in ('vendor/etc/permissions/android.hardware.uwb.xml',):
        if os.path.exists(os.path.join(R, feat)):
            os.remove(os.path.join(R, feat))

